<#
.SYNOPSIS
    Build FluoRaPressée for Windows (work/work_updater.md Step 3/4).

.DESCRIPTION
    The one build procedure, used both by hand and by .github/workflows/release.yml,
    so the two never drift apart.

      1. writes src\_build_info.py (commit and build date; not tracked by git)
      2. runs --smoke-test from source
      3. builds dist\FluoRaPressee\ with PyInstaller
      4. runs --smoke-test with the built executables
      5. (-Installer) builds packaging\Output\FluoRaPressee-Setup-<version>.exe

    Run from a Python environment that has requirements-oceanoptics.txt and
    requirements-build.txt installed. Never installs anything on this PC.

.PARAMETER Installer
    Also build the Inno Setup installer.

.PARAMETER Python
    Python executable to use (default: python).

.PARAMETER Iscc
    Path to ISCC.exe (default: the standard Inno Setup 6 location).
#>
param(
    [switch]$Installer,
    [string]$Python = "python",
    [string]$Iscc = ""
)

$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

$Repo = Split-Path -Parent $PSScriptRoot
Set-Location $Repo

function Invoke-Checked {
    param([string]$File, [string[]]$Arguments)
    & $File @Arguments
    if ($LASTEXITCODE -ne 0) {
        throw "'$File $($Arguments -join ' ')' failed with exit code $LASTEXITCODE"
    }
}

# --- version ---------------------------------------------------------------
$Version = (& $Python -c "from src.version import __version__; print(__version__)").Trim()
$NumericVersion = (& $Python -c "from packaging.version import Version; r = list(Version('$Version').release) + [0, 0, 0, 0]; print('.'.join(str(x) for x in r[:4]))").Trim()
Write-Host "Building FluoRaPressee $Version ($NumericVersion)"

# --- 1. build info -----------------------------------------------------------
$Commit = ""
try { $Commit = (git rev-parse --short=8 HEAD 2>$null).Trim() } catch { $Commit = "" }
$BuildDate = Get-Date -Format "yyyy-MM-dd"
Set-Content -Path (Join-Path $Repo "src\_build_info.py") -Encoding ascii -Value @(
    '"""Generated by packaging/build_windows.ps1 - not tracked by git."""',
    "COMMIT = `"$Commit`"",
    "BUILD_DATE = `"$BuildDate`""
)

# Logs of the smoke tests go to a throw-away data folder, never to real user data.
# The caller's own setting (e.g. a development data folder) is restored afterwards:
# run in the caller's session, clearing it would point the next start at real data.
$SmokeData = Join-Path ([System.IO.Path]::GetTempPath()) "FluoRaPressee-smoke-$PID"
$PreviousDataDir = $env:FLUORAPRESSEE_DATA_DIR
$env:FLUORAPRESSEE_DATA_DIR = $SmokeData
try {
    # --- 2. smoke test from source ------------------------------------------
    Invoke-Checked $Python @("main.py", "--smoke-test")
    Invoke-Checked $Python @("analysis_main.py", "--smoke-test")

    # --- 3. PyInstaller -------------------------------------------------------
    Invoke-Checked $Python @(
        "-m", "PyInstaller", "--noconfirm", "--clean",
        "--distpath", "dist", "--workpath", "build",
        "packaging\FluoRaPressee.spec"
    )

    # --- 4. smoke test of the build (windowed: output goes to the log file) ----
    foreach ($exe in @("FluoRaPressee.exe", "FluoRaPressee-Analysis.exe")) {
        $path = Join-Path $Repo "dist\FluoRaPressee\$exe"
        $process = Start-Process -FilePath $path -ArgumentList "--smoke-test" -Wait -PassThru
        $logs = Join-Path $SmokeData "logs"
        if (Test-Path $logs) {
            Get-ChildItem $logs -Filter "app-*.log" | Sort-Object LastWriteTime |
                Select-Object -Last 1 | ForEach-Object { Get-Content $_.FullName }
        }
        if ($process.ExitCode -ne 0) {
            throw "$exe --smoke-test failed with exit code $($process.ExitCode)"
        }
    }
}
finally {
    if ($null -eq $PreviousDataDir) {
        Remove-Item Env:FLUORAPRESSEE_DATA_DIR -ErrorAction SilentlyContinue
    } else {
        $env:FLUORAPRESSEE_DATA_DIR = $PreviousDataDir
    }
    Remove-Item $SmokeData -Recurse -Force -ErrorAction SilentlyContinue
}

# --- 5. installer --------------------------------------------------------------
if ($Installer) {
    if (-not $Iscc) {
        $Iscc = Join-Path ${env:ProgramFiles(x86)} "Inno Setup 6\ISCC.exe"
    }
    if (-not (Test-Path $Iscc)) {
        throw "ISCC.exe not found at $Iscc (install Inno Setup 6, or pass -Iscc)"
    }
    Invoke-Checked $Iscc @(
        "/DAppVersion=$Version",
        "/DAppVersionNumeric=$NumericVersion",
        "packaging\FluoRaPressee.iss"
    )
    Write-Host "Installer: packaging\Output\FluoRaPressee-Setup-$Version.exe"
}
