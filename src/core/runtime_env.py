"""Run mode, display version and process-wide named mutexes.

See work/work_updater.md 方針1/2 (run modes, version), 方針6 (the installer's
"running" mutex) and 方針13 (the instrument mutex). Everything else should ask this
module instead of looking at `sys.frozen` directly.

Qt-independent, so it can run before any GUI exists and be tested headlessly.
"""

from __future__ import annotations

import functools
import os
import string
import subprocess
import sys
from pathlib import Path

from src.version import __version__

APP_NAME = "FluoRaPressée"

# Shared with packaging/FluoRaPressee.iss. The rule that builds the name (see
# installer_mutex_name) is written there too; keep the two in step.
INSTALLER_MUTEX_PREFIX = "Global\\FluoRaPresseeRunning:"
INSTRUMENT_MUTEX_NAME = "Global\\FluoRaPresseeInstrument"

_ERROR_ALREADY_EXISTS = 183
_ERROR_ACCESS_DENIED = 5
_SYNCHRONIZE = 0x00100000
# Authenticated Users may open the mutex for SYNCHRONIZE only. Needed because the
# Ocean Optics driver tool runs elevated, and the installer (not elevated) must still
# be able to see its mutex - see 方針6 step 3.
_INSTALLER_MUTEX_SDDL = "D:(A;;0x00100000;;;AU)"

_ASCII_LOWER = str.maketrans(string.ascii_uppercase, string.ascii_lowercase)

# Handles that must stay open until the process exits. Closing one would let the
# mutex disappear while this process is still running.
_held_handles: list = []


# ---------------------------------------------------------------------------
# Run mode
# ---------------------------------------------------------------------------

def is_frozen() -> bool:
    return bool(getattr(sys, "frozen", False))


def runtime_kind() -> str:
    """"frozen" for a PyInstaller build, "source" when run with python."""
    return "frozen" if is_frozen() else "source"


def repo_root() -> Path:
    """The source tree's root (meaningful in source mode only)."""
    return Path(__file__).resolve().parents[2]


def app_dir() -> Path:
    """The folder holding the executable (frozen) or the repository root (source).

    Deliberately not resolved: the installer names the install folder the way it
    wrote it ({app}), and the installer mutex name must match that spelling.
    """
    if is_frozen():
        return Path(os.path.abspath(sys.executable)).parent
    return repo_root()


# ---------------------------------------------------------------------------
# Version
# ---------------------------------------------------------------------------

def build_info() -> dict | None:
    """Commit and build date baked into a frozen build, or None.

    src/_build_info.py is generated by packaging/build_windows.ps1 and is not
    tracked by git, so it only exists in builds.
    """
    try:
        from src import _build_info  # type: ignore[attr-defined]
    except Exception:
        return None
    return {
        "commit": getattr(_build_info, "COMMIT", None),
        "build_date": getattr(_build_info, "BUILD_DATE", None),
    }


@functools.lru_cache(maxsize=1)
def _git_short_hash() -> str | None:
    # Cached: display_version() is called for every saved spectrum and API status
    # request, and a git subprocess each time would be noticeable on the GUI thread.
    try:
        completed = subprocess.run(
            ["git", "rev-parse", "--short=8", "HEAD"],
            cwd=str(repo_root()),
            capture_output=True,
            text=True,
            timeout=3,
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        )
    except Exception:
        return None
    value = completed.stdout.strip()
    if completed.returncode != 0 or not value:
        return None
    return value


def display_version() -> str:
    """Version shown to people: "0.1.0b1+dev.g1a2b3c4d" from source, "0.1.0b1" built.

    Still valid PEP 440, but update comparisons use __version__ itself; a failed git
    call only drops the suffix and never raises.
    """
    if is_frozen():
        return __version__
    commit = _git_short_hash()
    return f"{__version__}+dev.g{commit}" if commit else __version__


def version_details() -> str:
    """One line for logs and the About box."""
    if is_frozen():
        info = build_info() or {}
        extras = ", ".join(
            str(value) for value in (info.get("commit"), info.get("build_date")) if value
        )
        return f"{__version__} (build {extras})" if extras else f"{__version__} (build)"
    return f"{display_version()} (source)"


# ---------------------------------------------------------------------------
# Installer mutex (方針6)
# ---------------------------------------------------------------------------

def installer_mutex_name(install_dir) -> str:
    """Name the installer and the app both derive from the install folder.

    The rule (also written in packaging/FluoRaPressee.iss): drop a trailing
    separator, turn "\\" into "/" (mutex names cannot contain a backslash after the
    namespace prefix), and lower-case A-Z only (mutex names are case-sensitive, and
    Inno Setup's Lowercase touches ASCII letters only).
    """
    path = str(install_dir).rstrip("\\/")
    path = path.replace("\\", "/").translate(_ASCII_LOWER)
    return INSTALLER_MUTEX_PREFIX + path


def _kernel32():
    import ctypes
    from ctypes import wintypes

    kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)
    kernel32.CreateMutexW.restype = wintypes.HANDLE
    kernel32.CreateMutexW.argtypes = [ctypes.c_void_p, wintypes.BOOL, wintypes.LPCWSTR]
    kernel32.CreateMutexExW.restype = wintypes.HANDLE
    kernel32.CreateMutexExW.argtypes = [
        ctypes.c_void_p, wintypes.LPCWSTR, wintypes.DWORD, wintypes.DWORD,
    ]
    kernel32.CloseHandle.restype = wintypes.BOOL
    kernel32.CloseHandle.argtypes = [wintypes.HANDLE]
    kernel32.LocalFree.restype = ctypes.c_void_p
    kernel32.LocalFree.argtypes = [ctypes.c_void_p]
    return kernel32


def _create_installer_mutex(name: str):
    """CreateMutexExW with SYNCHRONIZE access and an Authenticated-Users DACL.

    Returns (handle_or_None, last_error).
    """
    import ctypes
    from ctypes import wintypes

    class SECURITY_ATTRIBUTES(ctypes.Structure):
        _fields_ = [
            ("nLength", wintypes.DWORD),
            ("lpSecurityDescriptor", ctypes.c_void_p),
            ("bInheritHandle", wintypes.BOOL),
        ]

    kernel32 = _kernel32()
    advapi32 = ctypes.WinDLL("advapi32", use_last_error=True)
    convert = advapi32.ConvertStringSecurityDescriptorToSecurityDescriptorW
    convert.restype = wintypes.BOOL
    convert.argtypes = [
        wintypes.LPCWSTR, wintypes.DWORD, ctypes.POINTER(ctypes.c_void_p),
        ctypes.POINTER(wintypes.ULONG),
    ]

    descriptor = ctypes.c_void_p()
    if not convert(_INSTALLER_MUTEX_SDDL, 1, ctypes.byref(descriptor), None):
        return None, ctypes.get_last_error()
    try:
        attributes = SECURITY_ATTRIBUTES(
            ctypes.sizeof(SECURITY_ATTRIBUTES), descriptor, False
        )
        handle = kernel32.CreateMutexExW(
            ctypes.byref(attributes), name, 0, _SYNCHRONIZE
        )
        error = ctypes.get_last_error()
    finally:
        kernel32.LocalFree(descriptor)
    return (handle or None), error


def hold_installer_mutex(log=print, create=None) -> bool:
    """Mark this process as using the install folder, until it exits.

    Only frozen builds on Windows do this; a source checkout is never the installer's
    business (方針10). Failure is logged and ignored: this mutex only lets the
    installer ask the user to close the app, it does not guard the instrument.
    """
    if sys.platform != "win32" or not is_frozen():
        return False
    name = installer_mutex_name(app_dir())
    log(f"Installer mutex: {name}")
    try:
        handle, error = (create or _create_installer_mutex)(name)
    except Exception as exc:
        log(f"Warning: could not create the installer mutex: {exc}")
        return False
    if not handle:
        log(f"Warning: could not create the installer mutex (error {error}).")
        return False
    _held_handles.append(handle)
    return True


# ---------------------------------------------------------------------------
# Instrument mutex (方針13)
# ---------------------------------------------------------------------------

INSTRUMENT_ACQUIRED = "acquired"
INSTRUMENT_BUSY = "busy"                       # another process of this user
INSTRUMENT_BUSY_OTHER_USER = "busy_other_user"
INSTRUMENT_UNVERIFIED = "unverified"           # could not tell; carry on
INSTRUMENT_NOT_APPLICABLE = "not_applicable"   # not Windows


def acquire_instrument_mutex(create_mutex=None, get_last_error=None, close_handle=None):
    """Take Global\\FluoRaPresseeInstrument for the life of this process.

    Result handling follows the table in 方針13. The Win32 calls can be injected for
    tests; by default they come from kernel32 with use_last_error=True so the error
    code is read reliably.
    """
    if create_mutex is None:
        if sys.platform != "win32":
            return INSTRUMENT_NOT_APPLICABLE
        import ctypes

        kernel32 = _kernel32()
        create_mutex = kernel32.CreateMutexW
        get_last_error = ctypes.get_last_error
        close_handle = kernel32.CloseHandle

    try:
        handle = create_mutex(None, False, INSTRUMENT_MUTEX_NAME)
        error = get_last_error()
    except Exception as exc:
        print(f"Warning: could not check the instrument mutex: {exc}")
        return INSTRUMENT_UNVERIFIED

    if handle:
        if error == _ERROR_ALREADY_EXISTS:
            close_handle(handle)
            return INSTRUMENT_BUSY
        _held_handles.append(handle)
        return INSTRUMENT_ACQUIRED
    if error == _ERROR_ACCESS_DENIED:
        return INSTRUMENT_BUSY_OTHER_USER
    print(
        f"Warning: could not verify that no other FluoRaPressée is using the "
        f"instrument (error {error}); starting anyway."
    )
    return INSTRUMENT_UNVERIFIED
